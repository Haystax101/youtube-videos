const sh = (set, p0, l0, f0, p1, l1, f1) => ({ set, f: k => ({ p: lerpV(p0, p1 || p0, k), l: lerpV(l0, l1 || l0, k), fov: lerp(f0, f1 ?? f0, k) }) });
const push = (set, p, l, f, d = 0.25, df = 2) => { const dir = l.clone().sub(p).normalize(); return sh(set, p, l, f, p.clone().addScaledVector(dir, d), l, f - df); };
